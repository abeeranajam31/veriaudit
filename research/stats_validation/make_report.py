"""Render results/stats_validation/report.md from the committed CSVs (no hand-copied numbers).

Run (repo root): python research/stats_validation/make_report.py
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "results" / "stats_validation"
TESTS = ["signed_rank_wilcox", "signed_rank_pratt", "paired_t", "sign_flip_t", "sign_flip_raw", "mcnemar_majority", "gee_logit", "cond_logit"]


def main() -> None:
    rows = list(csv.DictReader((OUT / "rejection_rates.csv").open(encoding="utf-8")))
    meta = json.loads((OUT / "run_metadata.json").read_text(encoding="utf-8"))
    cov = list(csv.DictReader((OUT / "ci_coverage.csv").open(encoding="utf-8")))
    ci_m = list(csv.DictReader((OUT / "ci_methods.csv").open(encoding="utf-8"))) if (OUT / "ci_methods.csv").exists() else []
    dgps = {d["name"]: d for d in meta["dgps"]}
    by = {(r["dgp"], r["test"]): r for r in rows}
    order = list(dict.fromkeys(r["dgp"] for r in rows))
    lines = [
        "# Validation of the primary test — simulation results",
        "",
        "Generated by `research/stats_validation/make_report.py` from `rejection_rates.csv`, `ci_coverage.csv`, `ci_methods.csv`.",
        f"n = {meta['n_scenarios']} scenarios, {meta['n_samples_per_unit']} samples per unit; "
        f"{meta['n_sim_fast_tests']} simulations for rank/permutation/t/McNemar tests, "
        f"{meta['n_sim_model_tests']} for GEE and conditional logit, {meta['n_sim_coverage']} for CI coverage. "
        "Interpretation: docs/v2/statistical_validation.md.",
        "",
        "## Data-generating processes",
        "",
        "| DGP | Kind | True gap (pp) | Description |",
        "|---|---|---|---|",
        *[f"| {n} | {d['kind']} | {d['true_gap_pp']} | {d['description']} |" for n, d in dgps.items()],
    ]
    for alpha_key, title in (("reject_05", "α = .05"), ("reject_05_over_family", "α = .05/12 (confirmatory family)")):
        lines += [
            "",
            f"## Rejection rate at {title} (size under nulls, power under alternatives)",
            "",
            "| DGP | " + " | ".join(TESTS) + " |",
            "|---|" + "---|" * len(TESTS),
        ]
        for d in order:
            lines.append(f"| {d} | " + " | ".join(by[(d, t)][alpha_key] if (d, t) in by else "" for t in TESTS) + " |")
    lines += ["", "## Rejections in the wrong direction at α = .05 (alternatives)", "", "| DGP | " + " | ".join(TESTS) + " |", "|---|" + "---|" * len(TESTS)]
    for d in order:
        if dgps[d]["kind"] == "alternative":
            lines.append(f"| {d} | " + " | ".join(by[(d, t)]["wrong_direction_05"] if (d, t) in by else "" for t in TESTS) + " |")
    failed = [(r["dgp"], r["test"], r["n_failed_fits"]) for r in rows if r["n_failed_fits"] not in ("0", "")]
    lines += ["", "Model fits that failed (counted as non-rejections): " + (", ".join(f"{d} {t}: {n}" for d, t, n in failed) or "none")]
    lines += [
        "",
        "## Coverage of the 95% scenario-bootstrap CI and t-interval for the true mean gap",
        "",
        "| DGP | true gap pp | percentile bootstrap | t-interval | mean width pp |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {c['dgp']} | {c['true_gap_pp']} | {c['coverage_bootstrap_percentile']} | {c['coverage_t_interval']} | {c['mean_bootstrap_width_pp']} |" for c in cov
    ]
    if ci_m:
        lines += [
            "",
            "## Alternative CI methods at low rates (400 simulations, Monte-Carlo SE ≈ 0.011)",
            "",
            "| DGP | median non-zero differences | percentile | BCa | basic | t |",
            "|---|---|---|---|---|---|",
        ]
        lines += [
            f"| {c['dgp']} | {c['median_nonzero_differences']} | {c['coverage_percentile']} | {c['coverage_bca']} | {c['coverage_basic']} | {c['coverage_t']} |"
            for c in ci_m
        ]
    (OUT / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT / "report.md")


if __name__ == "__main__":
    main()
